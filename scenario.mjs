import { chromium } from 'playwright'
const [version, say] = process.argv.slice(2)
const C = 'http://127.0.0.1:3419/api/__accept'
const shot = (n) => `/tmp/acc5208/shots/${say}-${n}-${version}.png`
await fetch(`${C}/reset`)
await fetch(`${C}/set?version=${version}&say=${say}&autoDone=0`)
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, locale: 'zh-CN', timezoneId: 'Asia/Shanghai' })
const p = await ctx.newPage()
p.on('pageerror', (e) => console.log('pageerror', e.message))
await p.goto('http://127.0.0.1:3419/', { waitUntil: 'domcontentloaded' })
await p.waitForURL(/market/, { timeout: 60000 })
await p.waitForTimeout(5000)
const mod = await p.evaluate(async () => (await (await fetch('/src/stores/agentThread.ts')).text()).includes('heldBack'))
console.log(version, 'module has heldBack =', mod)
await p.locator('[data-testid="agent-entry"]').click()
const box = p.getByRole('textbox', { name: '输入问题或要做的事' }).last()
await p.waitForTimeout(2500); await p.screenshot({ path: shot('0-open') }); await box.waitFor({ timeout: 20000 })
await box.click(); await p.keyboard.type('把三份报告按评分表打分'); await p.keyboard.press('Enter')
await p.getByText('先把三份报告各读一遍').first().waitFor({ timeout: 20000 })
await p.waitForTimeout(800)
await box.click(); await p.keyboard.type('只看第 3 份'); await p.keyboard.press('Enter')
await p.waitForTimeout(2000)
await p.screenshot({ path: shot('1-refused') })
await fetch(`${C}/done`)
await p.waitForTimeout(3000)
await p.screenshot({ path: shot('2-settled') })
const st = await (await fetch(`${C}/state`)).json()
console.log(JSON.stringify({ version, say, server: st.messages, log: st.log.slice().reverse() }, null, 1))
await b.close()
