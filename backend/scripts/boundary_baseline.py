#!/usr/bin/env python3
"""Refresh the frozen baselines in `backend/.importlinter`.

    cd backend && uv run python scripts/boundary_baseline.py --update
    cd backend && uv run python scripts/boundary_baseline.py --update --freeze-new
    cd backend && uv run python scripts/boundary_baseline.py --dry-run
    cd backend && uv run python scripts/boundary_baseline.py          # report only

WHAT IT DOES. Runs the three contracts that carry a frozen baseline and rewrites
their `ignore_imports` block. C1 and C2 are shrink-only: an entry that no longer
matches is dropped, and an entry that *would* have to be added is reported and
refused unless `--freeze-new` accepts it on purpose.

C3 IS DIFFERENT, and the whole reason this script is not three lines shorter.
Its frozen list is a cycle-breaker set, and that set is not unique: recomputed
from scratch the same knot can come back as a different set of edges — measured
here, 21 live entries a recompute would silently drop and 66 it would add. So C3
is never recomputed. Its stale entries are read off `check_boundaries.py --json`
("No matches for ignored import <entry>."), which is import-linter's own verdict
on which frozen pairs matched nothing, and only those are dropped. A recomputed
C3 edge is never written, not even with `--freeze-new`: a reshuffled cut is not
new debt and freezing one is not the same act as accepting a real violation.

`--update` is shrink-only for C3, and `--freeze-new` does not change that.

The rewrite is verified before it is trusted: after writing, the script runs
`check_boundaries.py` on the new file and requires exit 0, then re-measures the
written file and requires the same baseline it just decided on. If either check
disagrees the original file is put back and the script exits 2 — a refresh that
leaves the check red, or that does not even agree with itself, is worse than no
refresh, because it looks like it worked.

Exit 0 wrote something / nothing had changed, 1 new violations need a decision,
2 could not judge or could not converge.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve()
BACKEND_ROOT = HERE.parents[1]
CONFIG_PATH = BACKEND_ROOT / ".importlinter"
CHECKER = HERE.parent / "check_boundaries.py"

#: The contracts `check_boundaries.py` claims to run, kept in step with it on
#: purpose: a declaration that lost one must not be "refreshed" into a smaller
#: check, and this script refuses to judge a file that no longer declares all
#: seven even though it only ever writes three of them.
CONTRACT_IDS = (
    "api-domain-core",
    "routes-touch-no-models",
    "domains-acyclic",
    "turn-layers",
    "turn-no-composition-imports",
    "realtime-no-turn",
    "turn-storage-purity",
)

#: The contracts that carry a generated frozen block. The four turn contracts
#: are structural and have no exemptions; a block on one of them is a shape this
#: script will not guess its way around.
BLOCK_CONTRACTS = ("api-domain-core", "routes-touch-no-models", "domains-acyclic")

#: The one contract whose stale entries come from the checker instead of a
#: recompute: its cycle-breaker set is not unique, so a fresh run names a
#: different cut of the same cycle.
CYCLE_CONTRACT = "domains-acyclic"

MARKER = "# --- frozen: existing violations, generated by scripts/boundary_baseline.py"
SUBHEAD = (
    "# Refresh with `--update` (drops entries that no longer match; new ones need "
    "`--freeze-new`)."
)
C3_SUBHEAD = (
    "# Refresh with `--update` (drops entries that no longer match; a recomputed "
    "cycle-breaker set is never added)."
)

HEADER_RE = re.compile(r"^\[importlinter(?::contract:(?P<id>[^\]]+))?\]\s*$")
WARNING_PREFIX = "No matches for ignored import "

OK, NEEDS_DECISION, CANNOT_JUDGE = 0, 1, 2


class ConfigShapeError(Exception):
    """The file has a frozen block this script will not guess its way around."""


def subhead_for(contract_id: str) -> str:
    """The subtitle the generated block of `contract_id` must carry."""
    return C3_SUBHEAD if contract_id == CYCLE_CONTRACT else SUBHEAD


# ---------------------------------------------------------------------------
# Reading and writing the file. A section is `[header]` plus the lines up to the
# next header. Prose may sit above a section's options; the frozen block is
# always the last thing in its section; anything unexpected after the marker is
# an error rather than something to silently drop, and an `ignore_imports` this
# script did not write is never quietly left behind for the contracts to honour.
# ---------------------------------------------------------------------------


def sections(text: str) -> tuple[str, list[tuple[str, str | None, list[str]]]]:
    """(preamble, [(header, contract id or None, body lines)])."""
    lines = text.split("\n")
    heads = [i for i, line in enumerate(lines) if HEADER_RE.match(line)]
    if not heads:
        raise ConfigShapeError("no [importlinter] section at all")
    preamble = "\n".join(lines[: heads[0]])
    out = []
    for position, start in enumerate(heads):
        end = heads[position + 1] if position + 1 < len(heads) else len(lines)
        match = HEADER_RE.match(lines[start])
        out.append((lines[start], match.group("id"), lines[start + 1 : end]))
    return preamble, out


def _is_ignore_imports(line: str) -> bool:
    """Whether `line` sets the `ignore_imports` option.

    Only the key matters, and it is compared case-insensitively: configparser
    lower-cases option names, so `Ignore_Imports =` is the same option and would
    otherwise slip past the guard. Splitting on the first `=` keeps a comment or
    a value that merely mentions the word from looking like the option.
    """
    key = line.lstrip().split("=", 1)[0].strip().lower()
    return key == "ignore_imports"


def _trim(body: list[str]) -> list[str]:
    kept = list(body)
    while kept and not kept[-1].strip():
        kept.pop()
    return kept


def _validate_entries(entries: list[str], where: str) -> None:
    """The generated block is sorted, deduplicated and free of wildcards."""
    if len(set(entries)) != len(entries):
        seen = sorted({entry for entry in entries if entries.count(entry) > 1})
        raise ConfigShapeError(f"{where}: a frozen entry is repeated: {seen}")
    if entries != sorted(entries):
        raise ConfigShapeError(
            f"{where}: the frozen entries are out of order; the block is sorted "
            "so a diff shows one line moving, not the whole list"
        )
    for entry in entries:
        if "*" in entry:
            raise ConfigShapeError(
                f"{where}: a frozen entry uses a wildcard ({entry!r}); an "
                "exemption that can absorb a file nobody looked at is not one"
            )


def split_block(body: list[str], subhead: str) -> tuple[list[str], list[str]]:
    """Split a section body into (lines to keep, frozen entries)."""
    index = next(
        (i for i, line in enumerate(body) if line.strip() == MARKER.strip()), None
    )
    if index is None:
        kept = _trim(body)
        if any(_is_ignore_imports(line) for line in kept):
            raise ConfigShapeError(
                "an `ignore_imports` block that this script did not generate is "
                "in the declarations; it would keep silencing imports without "
                "being counted, so it is not touched and nothing is written"
            )
        return kept, []

    kept = list(body[:index])
    if any(_is_ignore_imports(line) for line in kept):
        # An `ignore_imports` above the marker stays through a rewrite (only the
        # generated block is rebuilt), so it would keep silencing imports without
        # being counted — and when the generated block is empty it would not even
        # leave a stale warning to notice. Refuse rather than pass it through.
        raise ConfigShapeError(
            "an `ignore_imports` block sits above the generated block; it would "
            "keep silencing imports without being counted, so it is not touched "
            "and nothing is written"
        )
    tail = [line for line in body[index:] if line.strip()]
    if tail[:2] != [MARKER, subhead]:
        raise ConfigShapeError(
            f"the generated block after {MARKER!r} is not the shape this script "
            f"writes (expected {subhead!r}); it will not overwrite it"
        )
    rest = tail[2:]
    entries: list[str] = []
    if rest:
        if rest[0].strip() != "ignore_imports =":
            raise ConfigShapeError(
                f"expected `ignore_imports =` after the generated block header, "
                f"found {rest[0]!r}"
            )
        for line in rest[1:]:
            if not line.startswith("    ") or not line.strip():
                raise ConfigShapeError(
                    f"{line!r} follows the frozen entries but is not one; the "
                    "generated block must be the last thing in its section"
                )
            entries.append(line.strip())
    _validate_entries(entries, "the frozen block")
    return _trim(kept), entries


def parse(
    text: str,
) -> tuple[str, list[tuple[str, str | None, list[str], list[str]]]]:
    """(preamble, [(header, contract id, lines to keep, frozen entries)]).

    Validates the whole file: the three block-carrying contracts must each have
    a canonical block, a contract that is not one of them may not have one, and
    a contract this script does not know may not smuggle in an `ignore_imports`.
    """
    preamble, parsed = sections(text)
    out: list[tuple[str, str | None, list[str], list[str]]] = []
    for header, contract_id, body in parsed:
        if contract_id is None:
            out.append((header, None, _trim(body), []))
            continue
        if contract_id not in CONTRACT_IDS:
            if any(_is_ignore_imports(line) for line in body) or any(
                line.strip() == MARKER.strip() for line in body
            ):
                raise ConfigShapeError(
                    f"[importlinter:contract:{contract_id}] is not one of the "
                    f"contracts this script knows ({list(CONTRACT_IDS)}) but "
                    "carries a frozen block; refusing to leave it unmanaged"
                )
            out.append((header, contract_id, _trim(body), []))
            continue
        has_marker = any(line.strip() == MARKER.strip() for line in body)
        if contract_id in BLOCK_CONTRACTS and not has_marker:
            raise ConfigShapeError(
                f"[importlinter:contract:{contract_id}] must carry the generated "
                f"frozen block ({MARKER!r}); without it the contract's exemptions "
                "are not the ones being tracked"
            )
        if contract_id not in BLOCK_CONTRACTS and has_marker:
            raise ConfigShapeError(
                f"[importlinter:contract:{contract_id}] carries a frozen block, "
                "but only the contracts with frozen debt hold one; this script "
                "will not write a baseline for a structural contract"
            )
        kept, entries = split_block(body, subhead_for(contract_id))
        out.append((header, contract_id, kept, entries))
    return preamble, out


def read_entries(text: str) -> dict[str, list[str]]:
    """The entries currently frozen in the file, per contract id."""
    _, parsed = parse(text)
    return {
        contract_id: entries for _, contract_id, _, entries in parsed if contract_id
    }


def strip_baselines(text: str) -> str:
    """The same file with every frozen block removed — the contracts as declared."""
    preamble, parsed = parse(text)
    chunks = [preamble.rstrip("\n")]
    for header, _, kept, _ in parsed:
        chunks.append("\n".join([header, *kept]))
    return "\n\n".join(chunk.rstrip("\n") for chunk in chunks) + "\n"


def render_block(entries: list[str], subhead: str) -> list[str]:
    block = [MARKER, subhead]
    if entries:
        block.append("ignore_imports =")
        block.extend(f"    {entry}" for entry in entries)
    return block


def write_baselines(text: str, frozen: dict[str, list[str]]) -> str:
    preamble, parsed = parse(text)
    chunks = [preamble.rstrip("\n")]
    for header, contract_id, kept, _ in parsed:
        if contract_id is None or contract_id not in BLOCK_CONTRACTS:
            chunks.append("\n".join([header, *kept]).rstrip("\n"))
            continue
        if contract_id not in frozen:
            raise ConfigShapeError(
                f"[importlinter:contract:{contract_id}] is not one of the contracts "
                f"this script writes (it writes {list(frozen)})"
            )
        block = render_block(sorted(frozen[contract_id]), subhead_for(contract_id))
        chunks.append("\n".join([header, *kept, "", *block]).rstrip("\n"))
    return "\n\n".join(chunks) + "\n"


# ---------------------------------------------------------------------------
# Reading the violations off a run.
# ---------------------------------------------------------------------------


def entries_from_metadata(metadata: dict) -> list[str]:
    """The frozen expression for each violation in one contract's metadata.

    One line per *direct* import, because that is what `ignore_imports` matches:
    the layer contract reports chains of imports, and removing a link from a
    chain is what silences it. Exceptions are per module pair, so every line of
    each chain is frozen.
    """
    edges: set[tuple[str, str]] = set()

    # layers: invalid_dependencies -> routes -> chain -> links
    for dependency in metadata.get("invalid_dependencies", []):
        for route in dependency["routes"]:
            for link in route["chain"]:
                edges.add((link["importer"], link["imported"]))

    # forbidden: invalid_chains -> chains -> links
    for invalid in metadata.get("invalid_chains", []):
        for chain in invalid["chains"]:
            for link in chain:
                edges.add((link["importer"], link["imported"]))

    # acyclic_siblings: {package: {(importer, imported)}}
    for breakers in metadata.get("cycle_breakers_by_package", {}).values():
        edges.update(breakers)

    return sorted(f"{importer} -> {imported}" for importer, imported in edges)


def _entry_from_warning(warning: str) -> str:
    """The frozen entry a "no matches" warning names."""
    text = str(warning)
    if not text.startswith(WARNING_PREFIX) or not text.endswith("."):
        raise ConfigShapeError(f"unrecognised checker warning: {text!r}")
    return text[len(WARNING_PREFIX) : -1]


def check_tree(config_path: Path) -> tuple[int, dict[str, list[str]]]:
    """Run `check_boundaries.py --json` and return (exit code, stale by contract).

    The stale list is the checker's own answer to "which frozen pair matched
    nothing", which is the only authority this script trusts for C3. The exit
    code is kept because a run that came back broken is a run whose baseline
    must not be read as current.
    """
    result = subprocess.run(
        [sys.executable, str(CHECKER), "--config", str(config_path), "--json"],
        cwd=Path.cwd(),
        capture_output=True,
        text=True,
    )
    if result.returncode == CANNOT_JUDGE:
        reason = (result.stderr or result.stdout).strip()
        raise ConfigShapeError(f"the checker could not judge the tree: {reason}")
    lines = [line for line in result.stdout.splitlines() if line.strip()]
    if len(lines) != 1:
        raise ConfigShapeError(
            f"the checker printed {len(lines)} non-empty lines on stdout, "
            "expected its one JSON record"
        )
    try:
        record = json.loads(lines[0])
    except json.JSONDecodeError as exc:
        raise ConfigShapeError(f"the checker's record did not parse: {exc}") from exc
    stale: dict[str, list[str]] = {}
    for item in record.get("stale", []):
        stale.setdefault(item.get("file"), []).append(
            _entry_from_warning(item.get("why", ""))
        )
    return result.returncode, stale


def recompute(text: str) -> dict[str, list[str]]:
    """Every violation in `text` with the baselines stripped, per contract id.

    Only C1 and C2 are read from this: it names the edges a *recompute* calls
    violations, which for C3 is a different cut of the same cycles and not the
    set that was frozen.
    """
    sys.path.insert(0, str(Path.cwd()))
    try:
        from importlinter.api import read_configuration
        from importlinter.application.use_cases import (
            _register_contract_types,
            create_report,
        )
        from importlinter.application.user_options import UserOptions
    except Exception as exc:  # pragma: no cover - depends on the installed version
        raise ConfigShapeError(f"import-linter is not usable here: {exc!r}") from exc

    with tempfile.TemporaryDirectory(prefix="boundary-baseline-") as raw:
        path = Path(raw) / ".importlinter"
        path.write_text(strip_baselines(text))
        try:
            parsed = read_configuration(str(path))
        except Exception as exc:
            raise ConfigShapeError(
                f"the declarations could not be parsed: {exc!r}"
            ) from exc
        options = UserOptions(parsed["session_options"], parsed["contracts_options"])

        declared = [c["id"] for c in options.contracts_options]
        missing = [
            contract_id for contract_id in CONTRACT_IDS if contract_id not in declared
        ]
        if missing:
            raise ConfigShapeError(
                f"the declarations are missing {missing}; refusing to write a "
                "baseline for a check that no longer runs them"
            )

        try:
            _register_contract_types(options)
            report = create_report(options, cache_dir=None)
        except Exception as exc:
            raise ConfigShapeError(f"the contracts could not be run: {exc!r}") from exc

        if report.could_not_run:
            raise ConfigShapeError("import-linter could not run one of the contracts")

        # The report holds the contracts in declaration order (and a contract
        # that could not be built returns early, which the check above caught),
        # so the ids line up with the options the report was built from.
        checks = list(report.get_contracts_and_checks())
        if len(checks) != len(declared):
            raise ConfigShapeError(
                f"{len(checks)} contract(s) ran but {len(declared)} were declared; "
                "refusing to guess which baseline belongs to which"
            )
        return {
            contract_id: entries_from_metadata(check.metadata)
            for contract_id, (_, check) in zip(declared, checks, strict=True)
        }


def measure(text: str, stale: dict[str, list[str]]) -> dict[str, list[str]]:
    """The baseline `text` should carry.

    C1 and C2 are recomputed from their violations; C3 keeps its frozen cut and
    drops only the entries the checker called stale; the turn contracts hold
    nothing.
    """
    frozen = read_entries(text)
    recomputed = recompute(text)
    out: dict[str, list[str]] = {}
    for contract_id in CONTRACT_IDS:
        if contract_id == CYCLE_CONTRACT:
            dropped = set(stale.get(contract_id, ()))
            out[contract_id] = sorted(set(frozen.get(contract_id, ())) - dropped)
        elif contract_id in BLOCK_CONTRACTS:
            out[contract_id] = recomputed[contract_id]
        else:
            out[contract_id] = []
    return out


def _report_diffs(
    old: dict[str, list[str]], new: dict[str, list[str]], freeze_new: bool
) -> tuple[bool, list[str]]:
    """Print what changed; return (anything changed, additions still blocked)."""
    changes = False
    blocked: list[str] = []
    for contract_id in CONTRACT_IDS:
        before, after = set(old.get(contract_id, ())), set(new[contract_id])
        added, removed = sorted(after - before), sorted(before - after)
        if removed:
            changes = True
            print(
                f"{contract_id}: dropping {len(removed)} entry that no longer matches"
            )
            for entry in removed:
                print(f"  - {entry}")
        if added:
            changes = True
            if freeze_new:
                print(f"{contract_id}: freezing {len(added)} new violation(s)")
                for entry in added:
                    print(f"  + {entry}")
            else:
                blocked.extend(f"[{contract_id}] {entry}" for entry in added)
    return changes, blocked


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", default=str(CONFIG_PATH))
    parser.add_argument(
        "--update",
        action="store_true",
        help="write the refreshed baseline (without it this only reports)",
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="report what would change, write nothing"
    )
    parser.add_argument(
        "--freeze-new",
        action="store_true",
        help="also freeze C1/C2 violations not in the baseline yet, printing them",
    )
    args = parser.parse_args()

    config_path = Path(args.config)
    if not (Path.cwd() / "app" / "__init__.py").is_file():
        print(
            f"cannot judge: no app/ package in {Path.cwd()} — run this from the "
            "directory that holds it (backend/)",
            file=sys.stderr,
        )
        return CANNOT_JUDGE

    try:
        text = config_path.read_text()
        old = read_entries(text)
        missing = [
            contract_id for contract_id in CONTRACT_IDS if contract_id not in old
        ]
        if missing:
            raise ConfigShapeError(
                f"{config_path.name} does not declare {missing}; the check is "
                "designed to run all of "
                f"{list(CONTRACT_IDS)} and a refresh must not silently scale it back"
            )
        code, stale = check_tree(config_path)
        new = measure(text, stale)
    except ConfigShapeError as exc:
        print(f"cannot judge: {exc}", file=sys.stderr)
        return CANNOT_JUDGE
    except FileNotFoundError:
        print(f"cannot judge: no {config_path} to read", file=sys.stderr)
        return CANNOT_JUDGE

    changes, blocked = _report_diffs(old, new, args.freeze_new)

    if blocked:
        print(
            f"\n{len(blocked)} new violation(s) this baseline does not have. "
            "These are the thing the check exists to catch — fix them, or freeze "
            "them on purpose with --freeze-new:\n" + "\n".join(blocked),
            file=sys.stderr,
        )
        return NEEDS_DECISION

    if not changes:
        if code != OK:
            print(
                "cannot judge: the tree no longer passes check_boundaries.py "
                f"(exit {code}) and no frozen entry can be refreshed; the checker "
                "above says what broke",
                file=sys.stderr,
            )
            return CANNOT_JUDGE
        print(f"unchanged: {config_path.name} still matches the tree")
        return OK

    if args.dry_run:
        print(f"{config_path.name} would be rewritten, nothing written (dry run)")
        return OK

    if not args.update:
        print(
            f"{config_path.name} would be rewritten, nothing written "
            "(pass --update to write)"
        )
        return OK

    original = text
    written = write_baselines(text, new)
    config_path.write_text(written)

    # A refresh that leaves the check red looks like it worked, so verify it —
    # and verify that the file the checker just judged is the one that was
    # decided on, because a rewrite that does not agree with itself is a rewrite
    # nobody can reason about.
    try:
        vcode, vstale = check_tree(config_path)
        agrees = measure(written, vstale) == new
    except ConfigShapeError as exc:
        vcode, agrees = CANNOT_JUDGE, False
        print(f"cannot judge: {exc}", file=sys.stderr)
    if vcode != OK or not agrees:
        config_path.write_text(original)
        print(
            "cannot judge: the rewritten baseline does not converge — "
            f"check_boundaries.py exited {vcode}, the written file re-measured "
            f"{'the same baseline' if agrees else 'a different baseline'}, and "
            f"the original {config_path.name} has been restored",
            file=sys.stderr,
        )
        return CANNOT_JUDGE

    total = sum(len(entries) for entries in new.values())
    print(
        f"wrote {config_path.name}: {total} frozen entries across "
        f"{sum(bool(entries) for entries in new.values())} contract(s)"
    )
    return OK


if __name__ == "__main__":
    sys.exit(main())
