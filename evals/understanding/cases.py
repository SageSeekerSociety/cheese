def by_id(ids: list[str] | None) -> list[Case]:
    if not ids:
        return list(CASES)
    known = {c.id: c for c in CASES}
    missing = [i for i in ids if i not in known]
    if missing:
        raise SystemExit(f"no such case: {', '.join(missing)}")
    return [known[i] for i in ids]
