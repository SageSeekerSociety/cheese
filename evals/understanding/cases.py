"""The questions: 芝士 asks a person to decide, or answers 「没看懂」.

Every case starts from a real exchange on dev (2026-11, a read-only sample of
channel and task messages where a person said they did not understand), moved
into a university course project so no case is about the platform itself.
``seed`` names the exchange it grew from.

A case is the room as the agent would see it — what was asked, what was said,
what it did and found — plus what only the judge reads: who the reader is, and
the facts a right answer has to agree with. The reader never appears in the
agent's input, except in the ``memory`` variant, which is exactly the
question of whether carrying it there helps.

Cases marked ``holdout`` are not looked at while changing the rules text; they
check that a change did not only fit the cases it was tuned on.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Literal

Kind = Literal["task", "main_line"]
Mode = Literal["ask", "explain"]


@dataclass(frozen=True)
class Case:
    id: str
    mode: Mode
    #: Who answers: a task's 芝士 (asks with `cheese_ask`), or the channel's
    #: main line (asks the member with `chat_send`, after a task reported).
    kind: Kind
    title: str
    project: str
    #: Who is in the room, as the roster would name them.
    roster: tuple[str, ...]
    #: The task as it was opened: what was asked, in the member's words.
    brief: str
    #: What was said in the room before, oldest first: (speaker, text).
    said: tuple[tuple[str, str], ...]
    #: What the agent did and found (the run record, condensed).
    worked: tuple[str, ...]
    #: What comes after the work record: a person's message (speaker, text),
    #: the platform's report to a main line ("report", text), or nothing
    #: ("self", ""): the agent has just read its findings and goes on.
    trigger: tuple[str, str]
    #: Judge only: who reads the agent's answer.
    reader: str
    #: Judge only: what a correct message must agree with.
    facts: tuple[str, ...]
    seed: str
    #: The reader as the person's own notes would describe them (``memory``).
    reader_note: str = ""
    #: Criteria replacing the mode's own, for a case that tests something else.
    criteria: tuple[tuple[str, str], ...] = ()
    holdout: bool = False
    #: A main line's case: the task that reported, as `#n 标题`.
    task_ref: str = ""
    tags: tuple[str, ...] = field(default_factory=tuple)


