import { chromium } from 'playwright'
const [side, hold] = process.argv.slice(2)
const out = `/tmp/shots79/${side}-${hold}`
const browser = await chromium.launch({ executablePath: process.env.CHROME, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1100, height: 900 }, deviceScaleFactor: 1, locale: 'zh-CN' })
page.on('pageerror', (e) => console.log('PAGEERROR', e.message))
await page.goto(`http://127.0.0.1:5291/harness-ro.html?side=${side}&hold=${hold}`, { waitUntil: 'load', timeout: 60000 })
await page.getByText('打开「米洛」的技能面板').waitFor({ timeout: 30000 })
await page.getByText('打开「米洛」的技能面板').click()
const plus = page.getByRole('button', { name: '装到这台机器上' }).first()
await plus.waitFor({ timeout: 15000 })
if (hold === 'blocked') await page.locator('.skills__note', { hasText: 'alice 正在编辑' }).waitFor({ timeout: 8000 })
else await page.waitForFunction(() => { const b = document.querySelector('button[aria-label="装到这台机器上"]'); return b && !b.disabled }, null, { timeout: 10000 })
await page.waitForTimeout(hold === 'late' ? 1200 : 2500)
const disabled = await plus.isDisabled()
console.log(side, hold, 'plus disabled =', disabled)
await plus.click({ force: true, timeout: 3000 }).catch((e) => console.log('click:', e.message.split('\n')[0]))
if (hold === 'late') {
  await page.waitForTimeout(800)
  await page.keyboard.press('l')
  await page.waitForTimeout(800)
  await page.keyboard.press('i')
}
await page.waitForTimeout(2500)
await page.screenshot({ path: `${out}-dialog.png` })
await page.keyboard.press('Escape')
await page.waitForTimeout(600)
await page.locator('.h').screenshot({ path: `${out}-log.png` })
console.log((await page.locator('.log').innerText()).replace(/\n/g, ' | '))
await browser.close()
