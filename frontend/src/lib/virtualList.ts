// 列表虚拟化的门槛：一列**超过**这个行数才交给 `components/common/VirtualList.vue`，
// 以下照旧整列渲染。
//
// 为什么要有门槛，而不是一律虚拟化：整列渲染在这一版前端里不是降级路径，是常态。话题
// 列表靠 TransitionGroup 演 FLIP 换位——「我刚看的那一行被顶到上面去了」这件事要看得
// 见；看板底下那一列靠「哪一条刚掉进 done」的顺序说话。虚拟化只把窗口里的那几行挂在
// DOM 上，这两种「先后」演不出来（行进了又出，过渡还没走完就从树上摘了）。而收得下的
// 列表本来也不需要省那几个节点，所以阈值以内一行代码都不动——现成的测试、动画、键盘
// 走位全部照旧。
//
// 放在 `lib/` 而不是组件里：判断「这一组该不该虚拟化」的是 `useTopicRail`（数据那一
// 半），它不认识组件；两边必须用同一个数，不能各记一个。
export const VIRTUAL_LIST_THRESHOLD = 100

// 内容列表（diff 行、资料库的文件）虚拟化的门槛，比上面那个高：200。
//
// 上面 100 是给「行会换位」的列表定的（话题栏、看板 done 那一列）——它们在整列都在
// DOM 里时才演得出 FLIP 和「先后」。这几处不是换位列表，是**内容**：行与行之间只有
// 上下顺序，虚拟化省下来的是节点，代价是窗口外的行浏览器 Ctrl+F 摸不到、读屏也看不
// 见。200 是「正常大小的列表」的上限：这个数以内整列都在，真的长到会卡了才让出这份
// 可达性。
export const VIRTUAL_LIST_CONTENT_THRESHOLD = 200
