#!/usr/bin/env node
// Generates src/api/openapi.d.ts from the backend's OpenAPI document.
//
//   node scripts/gen-api-types.mjs    rewrite src/api/openapi.d.ts
//
// Neither half of this pair is committed. The output is not (frontend/.gitignore);
// the document behind it is asked of the backend, which builds it from the app
// instead of keeping a copy — the command is
// `uv run --frozen python -m scripts.export_openapi --stdout` in backend/. The
// two were 1.4 MB and 1.8 MB of text that every route change rewrote, so any two
// routes changed in parallel collided in them; with neither in the tree there is
// nothing left to collide.
//
// Everything that runs the ratchet generates the types first, through
// scripts/typecheck.mjs — so there is no stale copy to detect and no second
// command to remember. This script is the one place that asks the backend for
// the document, so the answer reaches every caller (pnpm run typecheck, the
// `task` task, the commit hook, the fast-check narrow run) without each of them
// knowing how to get it.
//
// The cost is that asking needs the backend's Python environment — uv, the
// interpreter, and the app's dependencies. That is what makes this the bigger
// half of the pair: a checkout without them can still edit and review the
// frontend, but not type-check it. Say so in plain words when it happens instead
// of letting a Node stack trace stand in for the reason.
//
// Types only — nothing here sends a request; the domain modules in src/api/ keep
// calling `request` and name their result types through src/cx_types.ts aliases
// of these.
import { spawnSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'

const HERE = dirname(fileURLToPath(import.meta.url))
const BACKEND = resolve(HERE, '../../backend')
const OUT = resolve(HERE, '../src/api/openapi.d.ts')
const HEADER =
  '// GENERATED by scripts/gen-api-types.mjs from the backend OpenAPI document. Do not edit:\n' +
  '// not committed — the type check runs this first, see scripts/typecheck.mjs.\n'

// The document is 1.8 MB of JSON, and a few hundred KB of stderr can ride along
// with it (the app's dependencies are chatty on import). Node's default 1 MB
// would truncate the document and fail to parse, so the ceiling is far above
// both — high only so a runaway process cannot eat the machine.
const MAX_OUTPUT = 64 * 1024 * 1024

// Ask the backend for the document. `--frozen` because a type check must not
// resolve or write the lockfile.
function buildSpec() {
  const result = spawnSync('uv', ['run', '--frozen', 'python', '-m', 'scripts.export_openapi', '--stdout'], {
    cwd: BACKEND,
    encoding: 'utf8',
    maxBuffer: MAX_OUTPUT,
  })
  if (result.error) {
    // The usual case is uv not being installed at all, which is ENOENT.
    const why = result.error.code === 'ENOENT' ? 'uv is not installed' : result.error.message
    console.error(
      `cannot build the backend's OpenAPI document: ${why}.\n` +
        `It is not committed — the frontend's types are generated from it, so a ` +
        `checkout needs the backend's Python environment: install uv, then run ` +
        `\`uv sync\` in ${BACKEND}.`
    )
    process.exit(1)
  }
  if (result.status !== 0) {
    console.error(
      `the backend failed to build its OpenAPI document (exit ${result.status}) ` +
        `in ${BACKEND}:\n${(result.stderr || '').trimEnd()}`
    )
    process.exit(1)
  }
  try {
    return JSON.parse(result.stdout)
  } catch (error) {
    console.error(
      `the backend's OpenAPI document is not JSON (${error.message}); ` + `first bytes: ${result.stdout.slice(0, 200)}`
    )
    process.exit(1)
  }
}

// FastAPI gives a route registered for several methods one operationId
// (`installer.download_binary` serves GET and HEAD), which the generator's
// validator refuses. The later ones get the method appended; `paths` is keyed by
// path and method and does not care.
function uniqueOperationIds(spec) {
  const seen = new Set()
  for (const item of Object.values(spec.paths ?? {})) {
    for (const [method, op] of Object.entries(item)) {
      if (!op || typeof op !== 'object' || !op.operationId) continue
      if (seen.has(op.operationId)) op.operationId = `${op.operationId}_${method}`
      seen.add(op.operationId)
    }
  }
  return spec
}

const ast = await openapiTS(uniqueOperationIds(buildSpec()))
writeFileSync(OUT, HEADER + astToString(ast))
