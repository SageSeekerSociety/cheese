#!/usr/bin/env node
// Generates src/api/openapi.d.ts from backend/openapi.json.
//
//   node scripts/gen-api-types.mjs    rewrite src/api/openapi.d.ts
//
// Both files are generated and neither is committed. This is the one reader of
// backend/openapi.json, so it regenerates that document from the app before it
// reads it — `uv run python -m scripts.export_openapi --schema` in backend/,
// the same command `be:openapi` (backend/Taskfile.yml) runs. A consumer that
// read a leftover copy instead would judge the frontend against a document the
// checkout no longer has, which is the drift the generation exists to prevent.
// Exits non-zero when the export fails or the document does not appear, so a
// failed generation stops the type check rather than letting it run stale.
//
// The output is not committed (frontend/.gitignore): a generated file nothing
// reads until the type check runs only made every route change rewrite it, and
// made any two routes changed in parallel collide. Everything that runs the
// ratchet generates it first, through scripts/typecheck.mjs — so there is no
// stale copy to detect and no second command to remember.
//
// Types only — nothing here sends a request; the domain modules in src/api/
// keep calling `request` and name their result types through src/cx_types.ts
// aliases of these.
import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'

const HERE = dirname(fileURLToPath(import.meta.url))
const BACKEND = resolve(HERE, '../../backend')
const SPEC = resolve(BACKEND, 'openapi.json')
const OUT = resolve(HERE, '../src/api/openapi.d.ts')
const HEADER =
  '// GENERATED by scripts/gen-api-types.mjs from backend/openapi.json. Do not edit:\n' +
  '// not committed — the type check runs this first, see scripts/typecheck.mjs.\n'

// FastAPI gives a route registered for several methods one operationId
// (`installer.download_binary` serves GET and HEAD), which the generator's
// validator refuses. The later ones get the method appended; `paths` is keyed by
// path and method and does not care.
function uniqueOperationIds(spec) {
  const seen = new Set()
  for (const item of Object.values(spec.paths ?? {})) {
    for (const [method, op] of Object.entries(item)) {
      if (!op || typeof op !== 'object' || !op.operationId) continue
      if (seen.has(op.operationId)) op.operationId = `${op.operationId}_${method}`
      seen.add(op.operationId)
    }
  }
  return spec
}

// Regenerate the document from the app. `--schema` writes only the schema: the
// untyped ratchet (backend/openapi-untyped.json) is tracked and only the backend
// lint job's `--check` judges it, so generation here never rewrites it. The
// child is the backend's own environment with the app importable, the same way
// scripts/check-request-paths.mjs runs the route collector.
function generate() {
  const result = spawnSync('uv', ['run', 'python', '-m', 'scripts.export_openapi', '--schema'], {
    cwd: BACKEND,
    encoding: 'utf8',
  })
  if (result.error) {
    console.error(`cannot generate backend/openapi.json: could not run the exporter (${result.error.message})`)
    process.exit(2)
  }
  if (result.status !== 0) {
    console.error('cannot generate backend/openapi.json: the exporter failed')
    console.error((result.stderr || result.stdout || '').trim())
    process.exit(2)
  }
}

generate()

// The exporter writes the document it just built; a read failure here is that
// write not landing, not a partial checkout. Exit 2 ("could not judge") so a
// failed generation stops the type check instead of reading a stale copy.
let raw
try {
  raw = readFileSync(SPEC, 'utf8')
} catch (error) {
  console.error(
    `cannot generate backend/openapi.json: the exporter ran but ${SPEC} could not be read (${error.message})`
  )
  process.exit(2)
}

const ast = await openapiTS(uniqueOperationIds(JSON.parse(raw)))
writeFileSync(OUT, HEADER + astToString(ast))
