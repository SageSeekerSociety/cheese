#!/usr/bin/env node
// Generates src/api/openapi.d.ts from backend/openapi.json.
//
//   node scripts/gen-api-types.mjs           rewrite src/api/openapi.d.ts
//   node scripts/gen-api-types.mjs --check   exit 1 when it is stale
//
// backend/openapi.json is the backend's own export (`uv run python -m
// scripts.export_openapi` in backend/), kept current by `export_openapi --check`
// in the backend lint job. This closes the second half: the types the frontend
// compiles against are exactly what that document says. Run both after
// changing a route. Types only — nothing here sends a request; the domain
// modules in src/api/ keep calling `request` and name their result types
// through src/cx_types.ts aliases of these.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'

const HERE = dirname(fileURLToPath(import.meta.url))
const SPEC = resolve(HERE, '../../backend/openapi.json')
const OUT = resolve(HERE, '../src/api/openapi.d.ts')
const HEADER =
  '// GENERATED by scripts/gen-api-types.mjs from backend/openapi.json. Do not edit:\n' +
  '// change the route or its response model, then rerun the two exports.\n'

// FastAPI gives a route registered for several methods one operationId
// (`installer.download_binary` serves GET and HEAD), which the generator's
// validator refuses. The later ones get the method appended; `paths` is keyed by
// path and method and does not care.
function uniqueOperationIds(spec) {
  const seen = new Set()
  for (const item of Object.values(spec.paths ?? {})) {
    for (const [method, op] of Object.entries(item)) {
      if (!op || typeof op !== 'object' || !op.operationId) continue
      if (seen.has(op.operationId)) op.operationId = `${op.operationId}_${method}`
      seen.add(op.operationId)
    }
  }
  return spec
}

const ast = await openapiTS(uniqueOperationIds(JSON.parse(readFileSync(SPEC, 'utf8'))))
const text = HEADER + astToString(ast)

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {
    // missing counts as stale
  }
  if (current !== text) {
    console.error('src/api/openapi.d.ts is stale: run `pnpm run gen:api-types` in frontend/')
    process.exit(1)
  }
  console.log('src/api/openapi.d.ts matches backend/openapi.json')
} else {
  writeFileSync(OUT, text)
}
