#!/bin/sh
# The mainland redirect, decided at container start (docker-entrypoint.sh).
#
#   mainland-redirect.sh NGINX_DIR
#
# MAINLAND_ENTRY is the origin visitors in China are sent to (https://okcheese.cn
# here). Empty — the default — writes a redirect that can never fire, so an
# image carries the rule and every deployment decides whether it runs it. That is
# deliberate: the rule has to reach a box that turns it on later without a
# rebuild, and a deployment that never turns it on must behave exactly as before.
#
# The hosts it applies to are this deployment's own, less the entry itself: the
# redirect must never send a visitor to the origin they are already on.
set -eu
NGINX_DIR="${1:?usage: mainland-redirect.sh NGINX_DIR}"
MAINLAND_DIR="$NGINX_DIR/mainland"

origin_of() {
  printf '%s' "$1" | tr -d '[:space:]' | tr 'A-Z' 'a-z' |
    sed -E 's|/+$||; s|^(https://[^/:]+):443$|\1|; s|^(http://[^/:]+):80$|\1|'
}
host_of() { printf '%s' "$1" | sed -E 's|^https?://||; s|:[0-9]+$||'; }
is_origin() { printf '%s' "$1" | grep -Eq '^https?://[a-z0-9.-]+(:[0-9]+)?$'; }
refuse() { echo "MAINLAND REDIRECT: $*" >&2; exit 1; }

entry=$(origin_of "${MAINLAND_ENTRY:-}")
switch=0
if [ -n "$entry" ]; then
  is_origin "$entry" || refuse "MAINLAND_ENTRY must be an origin such as https://okcheese.cn, not '$MAINLAND_ENTRY'"
  switch=1
fi

# The deployment's own names: the canonical origin, then any alias. A box whose
# FRONTEND_ALIASES is unset has none, and then only the canonical name is
# redirected — which is the deployment this ships to.
hosts=""
for name in $(printf '%s %s' "${FRONTEND_URL:-}" "${FRONTEND_ALIASES:-}" | sed -E 's/[][",]/ /g'); do
  case "$name" in
    http://*|https://*) ;;
    *) continue ;;
  esac
  host=$(host_of "$(origin_of "$name")")
  [ -n "$host" ] || continue
  [ "$host" = "$(host_of "$entry")" ] && continue
  case " $hosts " in *" $host "*) continue ;; esac
  hosts="$hosts $host"
done

entries=""
for host in $hosts; do
  entries="$entries    $host 1;
"
done

# Two files, both written whole and renamed into place: nginx re-reads this tree
# on every reload, and a half-written include takes the whole server down.
write() { # destination, contents
  printf '%s' "$2" > "$1.part" && mv -f "$1.part" "$1"
}

mkdir -p "$MAINLAND_DIR"
write "$MAINLAND_DIR/hosts.map" "# Generated by frontend/scripts/mainland-redirect.sh; do not edit.
map \$host \$mainland_our_origin {
    default 0;
$entries}
"

# Whether to redirect, as one answer: nginx has no boolean "and", and `if` does
# not nest, so every condition is folded into a map key instead.
if [ "$switch" = 1 ]; then
  decision="    # Our origin, a page navigation, a page, not signed in, in China, not
    # the desktop app — in that order.
    111010 1;
"
else
  decision="    # MAINLAND_ENTRY is unset: this deployment redirects no visitor.
"
fi
write "$MAINLAND_DIR/decide.map" "# Generated by frontend/scripts/mainland-redirect.sh; do not edit.
map \"\${mainland_our_origin}\${mainland_navigation}\${mainland_a_page}\${mainland_signed_in}\${is_china}\${mainland_is_desktop}\" \$mainland_to_entry {
    default 0;
$decision}
"

if [ "$switch" = 1 ]; then
  write "$MAINLAND_DIR/send.conf" "# Generated by frontend/scripts/mainland-redirect.sh; do not edit.
# Inputs: mainland/main.conf, mainland/decide.map.
if (\$mainland_to_entry) {
    return 302 $entry\$request_uri;
}
"
else
  # Off: the file still has to exist — nginx.conf includes it unconditionally —
  # but nothing in it can fire.
  write "$MAINLAND_DIR/send.conf" "# Generated by frontend/scripts/mainland-redirect.sh; do not edit.
# MAINLAND_ENTRY is unset, so this deployment redirects no visitor.
"
fi
