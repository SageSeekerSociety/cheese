import { chromium } from 'playwright'
const [version, path] = process.argv.slice(2)
const C = 'http://127.0.0.1:3419/api/__accept'
const shot = (n) => `/tmp/acc5208/shots/cut-${n}-${version}.png`
await fetch(`${C}/reset`); await fetch(`${C}/set?version=${version}&say=409&autoDone=3`)
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, locale: 'zh-CN', timezoneId: 'Asia/Shanghai' })
const p = await ctx.newPage()
p.on('pageerror', (e) => console.log('pageerror', e.message))
await p.goto('http://127.0.0.1:3419/', { waitUntil: 'domcontentloaded' })
await p.waitForURL(/market/, { timeout: 60000 })
await p.goto('http://127.0.0.1:3419' + path, { waitUntil: 'domcontentloaded' })
await p.waitForTimeout(6000)
console.log('url', p.url())
await p.locator('[data-testid="agent-entry"]').first().click().catch((e) => console.log('entry', e.message.slice(0, 80)))
await p.waitForTimeout(2000)
const box = p.getByRole('textbox', { name: '输入问题或要做的事' }).last()
await box.click(); await p.keyboard.type('把三份报告按评分表打分'); await p.keyboard.press('Enter')
await p.getByText('先把三份报告各读一遍').first().waitFor({ timeout: 20000 })
await p.waitForTimeout(1000)
await fetch(`${C}/cut`)
await p.waitForTimeout(1500)
await box.click(); await p.keyboard.type('只看第 3 份'); await p.keyboard.press('Enter')
await p.waitForTimeout(2000)
await p.screenshot({ path: shot('1-refused') })
await p.waitForTimeout(9000)
await p.screenshot({ path: shot('2-settled') })
const texts = await p.locator('.ap').first().innerText().catch(() => '')
console.log(texts.slice(0, 600))
const st = await (await fetch(`${C}/state`)).json()
console.log(JSON.stringify({ server: st.messages, log: st.log.slice().reverse() }, null, 1))
await b.close()
