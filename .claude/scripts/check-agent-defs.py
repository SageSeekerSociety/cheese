#!/usr/bin/env python3
"""Keep the two halves of the subagent dispatch contract true.

    python3 .claude/scripts/check-agent-defs.py [--root DIR]

Half one: every definition in `.claude/agents/*.md` is one the Agent tool can start, and
its `name` is the `subagent_type` a parent passes. Half two: nothing in the tree declares
a fan-out wider than the environment's cap of `CAP` concurrent subagents.

WHY THESE TWO ARE ONE GUARD. A parent starts a subagent by naming a type, and the number
of types it may have running at once is not its own to choose — the environment caps it.
A definition nobody can start and a topology the environment refuses are the same failure
seen from two sides, and both are silent: the Agent tool answers a launch with
`Async agent launched successfully` whether or not the type ever did anything, so a
definition with `model: kimi-k3` reads exactly like a working one.

WHY THE MODEL FIELD IS THE ONE THAT BITES. Claude Code's Agent tool accepts only Claude's
own aliases in its `model` parameter; a gateway model such as `kimi-k3` is reached another
way — as a `subagent_type` named by a definition the platform generates into the session's
config directory before launch (`docs/manual/dev/skills.md` §分身定义, generated by
`backend/app/domain/agent/gateway_usage.py`). So a `model:` line holding anything but an
alias is a definition that quietly runs on the wrong model, or on none.

WHY `model-*.md` IS RESERVED. That filename is the generated catalog's, and those files
are wiped and rewritten before every launch. A checked-in one does not survive, and its
`name` — the cleaned model id — is already taken by the generated definition, so the type
the parent asks for is not the one it gets.

WHY THE FAN-OUT CHECK IS NOT A COPY OF tiers.py's OWN SELF-TEST. That self-test compares
the table against a list of expected counts living in the same file: whoever adds a tier
edits both and it stays green, including at six finders. This guard compares the table
against the cap, which is not in that file, so widening a tier cannot pass by editing its
own expectation. `CAP` here is 4 because the environment runs at most four subagents at
once (`tiers.py`'s docstring, measured when its topologies were set).

THE FORM AND THE FIX. Every finding is one line to stderr, `<path>:<line>: <what and how
to fix it>`, and the exit code is the verdict. Nothing here is a warning.
"""

from __future__ import annotations

import argparse
import re
import sys
import types
from pathlib import Path
from typing import NamedTuple

#: How many subagents the environment runs at once. A topology's stages run one after
#: another, so what a tier spends is its widest stage, not the sum of its stages.
CAP = 4

#: The Agent tool's `model` parameter takes these and nothing else. `inherit` is what a
#: definition omits the line for, and is accepted so that saying it out loud is legal.
CLAUDE_MODEL_ALIASES = frozenset({"sonnet", "opus", "haiku", "fable", "inherit"})

#: A definition's `name` is a `subagent_type`: it travels as a value, so it stays a slug.
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")

#: A top-level `key: value` line of the frontmatter.
KEY_RE = re.compile(r"^([A-Za-z][A-Za-z0-9_-]*):(.*)$")

#: A `description:` whose value is a block-scalar header is not a description: the text is
#: the indented lines under it, so the header alone says nothing. The header may carry a
#: chomping sign and an indentation indicator (`>`, `|-`, `|2`, `>2-`), so it is matched as
#: a shape rather than listed.
BLOCK_MARKER_RE = re.compile(r"^[|>][+-]?\d*[+-]?$")

#: A byte-order mark, which an editor may leave in front of the opening `---`. `str.strip()`
#: does not remove it, so a file that is otherwise well formed would read as having no
#: frontmatter at all — a finding about a file that has nothing wrong with it.
BOM = chr(0xFEFF)


class Finding(NamedTuple):
    path: str
    line: int
    message: str


def scalar(raw: str) -> tuple[str, bool]:
    """A frontmatter value as `(text, was quoted)`: quotes removed, a trailing `#` comment
    dropped, and whether the YAML value was written as a quoted string.

    Both shapes are ordinary YAML — `model: "sonnet"` and `model: sonnet  # why` name the
    same alias — so reading them as text without this would report a legal definition.
    The flag is what tells `description: ">"` (the character) from `description: >` (a
    block header), which look alike once the quotes are gone. A `#` that no space
    precedes is part of the value, as YAML says."""
    text = raw.strip()
    quote = text[:1]
    if quote in ("'", '"'):
        i = 1
        while i < len(text):
            if quote == "'" and text[i : i + 2] == "''":
                i += 2  # two single quotes inside a single-quoted scalar are one quote
                continue
            if text[i] == quote:
                break
            i += 1
        rest = text[i + 1 :].strip() if i < len(text) else ""
        if i < len(text) and (not rest or rest.startswith("#")):
            body = text[1:i]
            # The interior of a double-quoted scalar is taken as written: only the single
            # quotes state an escape, and backslash escapes do not change any value the
            # guard judges.
            return (body.replace("''", "'") if quote == "'" else body), True
    comment = re.search(r"(?:^|\s)#", text)
    if comment:
        text = text[: comment.start()].strip()
    return text, False


def frontmatter(text: str) -> dict[str, dict] | None:
    """The `---`-fenced frontmatter as `{key: {"value", "line", "body"}}`, or None when the
    file has no such block. The values are read as text rather than through a YAML
    parser: no `.claude/scripts` guard may need a dependency to run, and the shape here —
    a flat mapping whose keys are simple and whose only block values are descriptions — is
    exactly what a session's definitions use."""
    lines = text.removeprefix(BOM).splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if end is None:
        return None

    keys: dict[str, dict] = {}
    current: str | None = None
    for offset, line in enumerate(lines[1:end], start=2):
        if not line.strip():
            continue
        if line[:1] in (" ", "\t"):
            # An indented line belongs to the key above it: a block scalar's text, or a
            # nested mapping. Either way the key has content.
            if current is not None:
                keys[current]["body"].append(line.strip())
            continue
        match = KEY_RE.match(line)
        if match:
            current = match.group(1)
            value, quoted = scalar(match.group(2))
            keys[current] = {"value": value, "quoted": quoted, "line": offset, "body": []}
    return keys


def has_text(entry: dict) -> bool:
    """True when a frontmatter key carries text, inline or as a block scalar. A block
    header with nothing indented under it, and an empty quoted value, both say nothing —
    but a quoted `>` is that character, so the block-header test only applies unquoted."""
    if entry["body"]:
        return True
    value = entry["value"]
    if not value:
        return False
    return entry["quoted"] or BLOCK_MARKER_RE.match(value) is None


def read_definition(path: Path, rel: str) -> tuple[str | None, Finding | None]:
    """The file's text, or the finding that says why it could not be read. A definition
    that is not UTF-8 is reported like any other problem and the rest of the tree is still
    judged: one bad byte must not turn the run into a traceback that hides the others."""
    try:
        return path.read_text(encoding="utf-8"), None
    except UnicodeDecodeError:
        return None, Finding(rel, 1, "这个文件不是 UTF-8：守卫读不出它的内容，判不了。"
                                     "用 UTF-8 重存一遍（编辑器里通常是「以 UTF-8 保存」）")


def check_definition(path: Path, rel: str) -> list[Finding]:
    findings: list[Finding] = []
    text, unreadable = read_definition(path, rel)
    if unreadable is not None:
        return [unreadable]
    keys = frontmatter(text or "")
    if keys is None:
        return [Finding(rel, 1, "没有 `---` 围起来的 frontmatter：补上 name 和 description 两行，"
                                "如 `name: <文件名>`、`description: <这个类型什么时候该用>`")]

    # A fix that is itself refused is no fix: when the file name is not a slug either, or
    # is one the reserved-name rule refuses below (`model-*`), naming it as the one to
    # write sends the reader straight at a second finding.
    stem_is_free = bool(NAME_RE.match(path.stem)) and not path.stem.startswith("model-")
    slug_fix = (
        f"改成 `name: {path.stem}`"
        if stem_is_free
        else f"这个名字和文件名 {path.name} 都要改：两边都只能用小写字母、数字和连字符"
    )
    name = keys.get("name")
    if name is None or not has_text(name):
        hint = (
            f"补一行 `name: {path.stem}`"
            if stem_is_free
            else f"补一行 `name: <slug>`，并把文件名 {path.name} 一起改成同一个 slug"
        )
        findings.append(Finding(rel, 1, "缺 `name`：它就是这个定义的 subagent_type，" + hint))
    else:
        value = name["value"]
        if not NAME_RE.match(value):
            findings.append(Finding(rel, name["line"],
                                    f"`name: {value}` 不是 slug：只能用小写字母、数字和连字符，{slug_fix}"))
        elif value != path.stem:
            findings.append(Finding(rel, name["line"],
                                    f"`name: {value}` 和文件名 {path.name} 不一致："
                                    f"两个名字指同一个定义，任选一边改齐（{slug_fix}）"))

    description = keys.get("description")
    if description is None or not has_text(description):
        findings.append(Finding(rel, 1, "缺 `description`：父 agent 在类型清单里读到的就是这一行，"
                                        "写清这个类型什么时候该用，一行就够"))

    model = keys.get("model")
    if model is not None:
        value = model["value"].lower()
        if value not in CLAUDE_MODEL_ALIASES:
            findings.append(Finding(rel, model["line"],
                                    f"`model: {model['value']}` 不是 Claude 的别名：Agent 工具的 model 参数"
                                    "只认 " + " / ".join(sorted(CLAUDE_MODEL_ALIASES))
                                    + "。要派到别的模型上，别改这一行——把 `model` 删掉，"
                                    "改用那个模型自己的 subagent_type（平台每次启动前生成的 "
                                    "`model-<模型 id>.md`），并在 description 里写明"))

    tools = keys.get("tools")
    if tools is not None and not has_text(tools):
        findings.append(Finding(rel, tools["line"],
                                "`tools:` 后面是空的：要么删掉这一行（等于给全部工具），"
                                "要么写上工具名，如 `tools: Bash, Read`"))

    if path.stem.startswith("model-"):
        findings.append(Finding(rel, 1,
                                "`model-*.md` 这个文件名归平台生成的模型目录所有，它每次启动前都会被清掉重写，"
                                "里面的 name 也已经占着：给项目自己的定义换个不以 model- 开头的名字"))
    return findings


def duplicate_names(root: Path, paths: list[Path]) -> list[Finding]:
    """Two definitions with one `name` are one subagent_type with two bodies: the session
    picks one and nobody can tell which."""
    seen: dict[str, str] = {}
    findings: list[Finding] = []
    for path in paths:
        text, unreadable = read_definition(path, path.relative_to(root).as_posix())
        if unreadable is not None:
            continue  # `check_definition` already reported this file
        keys = frontmatter(text or "")
        if not keys or not has_text(keys.get("name", {"value": "", "body": []})):
            continue
        name = keys["name"]["value"]
        rel = path.relative_to(root).as_posix()
        if name in seen:
            findings.append(Finding(rel, keys["name"]["line"],
                                    f"`name: {name}` 和 {seen[name]} 重名：一个 subagent_type 只能有一个定义，"
                                    "改名或合并"))
        else:
            seen[name] = rel
    return findings


def check_definitions(root: Path) -> list[Finding]:
    agents = root / ".claude" / "agents"
    if not agents.is_dir():
        return [Finding(".claude/agents", 0,
                        "找不到 .claude/agents/：这个守卫读的就是它，目录不在就没法判断。"
                        "补回目录，或者连这个守卫一起删掉")]
    paths = sorted(p for p in agents.glob("*.md") if p.is_file())
    findings: list[Finding] = []
    for path in paths:
        findings.extend(check_definition(path, path.relative_to(root).as_posix()))
    return findings + duplicate_names(root, paths)


def load_tiers(path: Path):
    """The review tiering module, executed from its source held in memory.

    Not through an import loader: a loader leaves a `__pycache__` beside the file it reads,
    and — because Python invalidates that cache on the source's mtime and size — an edit
    that keeps the size and lands inside the same second as the last run would be answered
    from the bytecode of the version before it. The guard would then read the topology from
    before the widening and pass the one change it exists to refuse. Executing the text it
    just read leaves no cache to be stale, and writes nothing into the tree it examines."""
    module = types.ModuleType("_agent_defs_tiers")
    module.__file__ = str(path)
    exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), module.__dict__)
    return module


def check_fan_out(root: Path) -> list[Finding]:
    """Every declared topology fits inside the cap. The letters are read off the module
    rather than listed here, so a tier added tomorrow is judged without editing this."""
    path = root / ".claude" / "pr-review" / "tiers.py"
    rel = ".claude/pr-review/tiers.py"
    if not path.is_file():
        return [Finding(rel, 0, "找不到这个文件：子代理扇出的声明都在它里面，读不到就没法判断"
                                "（这一条不是「没问题」）")]
    module = load_tiers(path)
    findings: list[Finding] = []
    letters = [row[0] for row in (*module.TIERS, module.MECHANICAL)]
    for letter in sorted(letters):
        topology = module.topology(letter)
        try:
            counts = [topology["finders"], topology["refuters"], topology["claim"]]
        except (KeyError, TypeError) as exc:
            findings.append(Finding(rel, 0, f"{letter} 档的拓扑读不出 finders/refuters/claim（{exc}）："
                                            "补上这三个计数，别让守卫猜"))
            continue
        if any(not isinstance(count, int) or count < 0 for count in counts):
            findings.append(Finding(rel, 0, f"{letter} 档的拓扑计数 {counts} 不是非负整数："
                                            "阶段数是个数，不是别的"))
            continue
        in_flight = max(counts)
        if in_flight > CAP:
            findings.append(Finding(rel, 0,
                                    f"{letter} 档同时最多 {in_flight} 个分身，超过环境的 {CAP} 个上限："
                                    "阶段是一个接一个跑的，单轮并发取最宽的那一阶段，不是各阶段之和；"
                                    f"要更多找茬就加到后面的阶段，别同时开到 {in_flight} 个"))
    return findings


def check(root: Path) -> list[Finding]:
    return check_definitions(root) + check_fan_out(root)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    args = parser.parse_args()
    root = args.root.resolve()
    findings = check(root)
    for finding in findings:
        where = f"{finding.path}:{finding.line}" if finding.line else finding.path
        print(f"{where}: {finding.message}", file=sys.stderr)
    if findings:
        print(f"分身定义守卫发现 {len(findings)} 个问题", file=sys.stderr)
        return 1
    print("分身定义守卫通过")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
